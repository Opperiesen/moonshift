import { readFile, writeFile } from 'node:fs/promises';

import YAML from 'yaml';

const source = 'specs/001-supervised-autonomous-loop/contracts/http-api.openapi.yaml';
const executionSource =
  'specs/001-supervised-autonomous-loop/contracts/execution-backend.schema.json';
const target = 'packages/contracts/src/generated.ts';
const openapi = YAML.parse(await readFile(source, 'utf8'));
const executionBackend = JSON.parse(await readFile(executionSource, 'utf8'));
const schemas = openapi.components.schemas;
const backendEventSchema = executionBackend.$defs.backendEvent;
const observableSchema = executionBackend.$defs.observable;
const arrays = [
  ['PROJECT_STATES', schemas.ProjectState.enum],
  ['TASK_STATES', schemas.TaskState.enum],
  ['EXECUTION_STATES', schemas.ExecutionState.enum],
  ['PRESENCE_STATES', schemas.PresenceState.enum],
  ['PRESENCE_SOURCE_TYPES', schemas.PresenceView.properties.sourceType.enum],
  ['AGENT_IDENTITY_STATES', schemas.AgentIdentityState.enum],
];
const lines = [
  '// Generated by scripts/generate-contract-types.mjs. Do not edit by hand.',
  `// Sources: ${source} and ${executionSource}.`,
  '// The approved schemas remain authoritative; these derivatives are non-authoritative.',
  '',
];
for (const [name, values] of arrays) {
  lines.push(`export const ${name} = ${JSON.stringify(values)} as const;`);
  const singular = name
    .toLowerCase()
    .split('_')
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join('')
    .replace(/States$/, 'State')
    .replace(/Types$/, 'Type');
  lines.push(`export type ${singular} = (typeof ${name})[number];`, '');
}
const personaStates = ['ACTIVE', 'DISABLED', 'ARCHIVED'];
const specialistStates = ['CREATED', 'ACTIVE', 'PAUSED', 'COMPLETED', 'FAILED', 'ARCHIVED'];
for (const state of [...personaStates, ...specialistStates]) {
  if (!schemas.AgentIdentityState.enum.includes(state)) {
    throw new Error(`Identity lifecycle state ${state} is absent from the approved OpenAPI schema`);
  }
}
lines.push(
  `export const PERSONA_IDENTITY_STATES = ${JSON.stringify(personaStates)} as const;`,
  `export const SPECIALIST_IDENTITY_STATES = ${JSON.stringify(specialistStates)} as const;`,
  '',
);

function tsType(schema) {
  if (Object.hasOwn(schema, 'const')) return JSON.stringify(schema.const);
  if (Array.isArray(schema.enum))
    return schema.enum.map((value) => JSON.stringify(value)).join(' | ');
  if (schema.$ref !== undefined) return 'string';
  if (schema.type === 'string') return 'string';
  if (schema.type === 'integer' || schema.type === 'number') return 'number';
  if (schema.type === 'boolean') return 'boolean';
  if (schema.type === 'object') {
    const required = new Set(schema.required ?? []);
    const fields = Object.entries(schema.properties ?? {}).map(
      ([name, property]) => `readonly ${name}${required.has(name) ? '' : '?'}: ${tsType(property)}`,
    );
    return `{ ${fields.join('; ')} }`;
  }
  throw new Error(`Unsupported approved schema derivative: ${JSON.stringify(schema)}`);
}

const eventTypeSchema = backendEventSchema.properties.eventType;
lines.push(`export type BackendEventType = ${tsType(eventTypeSchema)};`, '');

function emitInterface(name, schema, typeOverrides = {}) {
  const required = new Set(schema.required ?? []);
  lines.push(`export interface ${name} {`);
  for (const [propertyName, propertySchema] of Object.entries(schema.properties)) {
    const optional = required.has(propertyName) ? '' : '?';
    const propertyType = typeOverrides[propertyName] ?? tsType(propertySchema);
    lines.push(`  readonly ${propertyName}${optional}: ${propertyType};`);
  }
  lines.push('}', '');
}

emitInterface('BackendObservable', observableSchema);
emitInterface('BackendEvent', backendEventSchema, {
  eventType: 'BackendEventType',
  observable: 'BackendObservable',
});
const generated = `${lines.join('\n').trimEnd()}\n`;
if (process.argv.includes('--check')) {
  const current = await readFile(target, 'utf8');
  if (current !== generated)
    throw new Error(`${target} is not reproducible from ${source} and ${executionSource}`);
} else {
  await writeFile(target, generated);
}
